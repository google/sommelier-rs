    #[test]
    fn on_commit_forwards_content_type_and_input_type() {
        // Verify the full pipeline: set_content_type → on_commit → host
        // receives set_content_type (opcode 6) + set_input_type (opcode 6 on ext).
        let mut ctx = Context::new_for_test(false, false, vec![]);

        let guest_text_input_id = 100u32;
        let host_v1_id = 200u32;
        let guest_seat = 5u32;
        let host_seat = 50u32;
        let guest_surface = 7u32;
        let host_surface = 70u32;
        ctx.shadow_table.map_id(guest_seat, host_seat);
        ctx.shadow_table.map_id(guest_surface, host_surface);

        ctx.text_inputs.insert(
            guest_text_input_id,
            crate::state::TextInputState {
                host_v1_id,
                host_ext_id: 201,
                guest_seat,
                active_surface: Some(guest_surface),
                ..Default::default()
            },
        );

        // Set content type (purpose=8 = password)
        ctx.last_sender_id = guest_text_input_id;
        let mut handler = TextInputV3Handler;
        handler.on_set_content_type(&mut ctx, 0, 8);

        // Verify state is cached
        let state = ctx.text_inputs.get(&guest_text_input_id).unwrap();
        assert!(state.content_type_changed);
        assert_eq!(state.content_purpose, 8);

        // Now commit — should forward content type to host
        handler.on_commit(&mut ctx);

        // Look for set_content_type (opcode 6) and set_input_type (opcode 6) messages
        let has_content_type = ctx.client_to_host_queue.iter().any(|(msg, _)| {
            let sender = u32::from_ne_bytes(msg[0..4].try_into().unwrap());
            let opcode = (u32::from_ne_bytes(msg[4..8].try_into().unwrap()) & 0xffff) as u16;
            sender == host_v1_id && opcode == ZWP_TEXT_INPUT_V1_REQ_SET_CONTENT_TYPE
        });
        assert!(has_content_type, "set_content_type must be sent to host");

        let has_input_type = ctx.client_to_host_queue.iter().any(|(msg, _)| {
            let sender = u32::from_ne_bytes(msg[0..4].try_into().unwrap());
            let opcode = (u32::from_ne_bytes(msg[4..8].try_into().unwrap()) & 0xffff) as u16;
            sender == 201 && opcode == ZCR_EXTENDED_TEXT_INPUT_V1_REQ_SET_INPUT_TYPE
        });
        assert!(has_input_type, "set_input_type must be sent to host ext object");

        // content_type_changed must be cleared after commit
        let state = ctx.text_inputs.get(&guest_text_input_id).unwrap();
        assert!(
            !state.content_type_changed,
            "content_type_changed must be cleared after commit"
        );
    }
