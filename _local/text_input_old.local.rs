/// Fetch-and-increment the per-text-input done serial.
///
/// Each synthesized `zwp_text_input_v3.done` event must carry a monotonically
/// increasing serial so the guest can correlate `commit` requests to the
/// matching server-side batch. Wrapping addition is used: a 32-bit serial
/// wraps after ~4 billion events, which is safe in practice (the guest
/// processes each batch before the counter can wrap on a local socket).
///
/// Returns `0` as a fallback when the text input state is not found. This
/// edge case should never occur in practice (the caller always has a valid
/// `guest_id`), but using a sentinel rather than panicking keeps the proxy
/// resilient against unexpected protocol orderings.
fn next_done_serial(ctx: &mut crate::state::Context, guest_id: u32) -> u32 {
    if let Some(state) = ctx.text_inputs.get_mut(&guest_id) {
        let s = state.done_serial;
        state.done_serial = state.done_serial.wrapping_add(1);
        s
    } else {
        log::warn!(
            "next_done_serial: no text_input state for guest_id={}; sending serial=0",
            guest_id
        );
        0
    }
}

/// Send a synthesized `zwp_text_input_v3.done` event to the guest.
///
/// This is the final event in a v3 transactional batch. All preceding events
/// (preedit_string, commit_string, delete_surrounding_text) within the batch
/// are only applied by the guest once it receives this done event.
fn send_v3_done(ctx: &mut crate::state::Context, guest_id: u32) {
    let serial = next_done_serial(ctx, guest_id);
    let mut builder = MessageBuilder::new();
    builder.write_u32(serial);
    let msg = builder.build_message(guest_id, ZWP_TEXT_INPUT_V3_EVT_DONE);
    ctx.host_to_client_queue.push((msg, Vec::new()));
}

