    #[test]
    fn on_disable_clears_pending_state() {
        // Per the v3 spec, after disable the text input state is "void".
        // Pending content type, surrounding text, and cursor rect should be
        // cleared so a subsequent enable+commit doesn't re-send stale data.
        let mut ctx = Context::new_for_test(false, false, vec![]);

        let guest_text_input_id = 100u32;
        ctx.text_inputs.insert(
            guest_text_input_id,
            crate::state::TextInputState {
                host_v1_id: 200,
                host_ext_id: 201,
                guest_seat: 5,
                enabled: true,
                surrounding_text: Some(("hello".to_string(), 5, 5)),
                content_hint: 3,
                content_purpose: 1,
                content_type_changed: true,
                cursor_rect: Some((10, 20, 30, 40)),
                ..Default::default()
            },
        );

        ctx.last_sender_id = guest_text_input_id;
        let mut handler = TextInputV3Handler;
        let action = handler.on_disable(&mut ctx);
        assert_eq!(action, Action::Drop);

        let state = ctx.text_inputs.get(&guest_text_input_id).unwrap();
        assert!(!state.enabled, "enabled must be false after disable");
        assert!(state.enabled_changed, "enabled_changed must be set");
        assert!(
            state.surrounding_text.is_none(),
            "surrounding_text must be cleared on disable"
        );
        assert!(
            !state.content_type_changed,
            "content_type_changed must be cleared on disable"
        );
        assert!(
            state.cursor_rect.is_none(),
            "cursor_rect must be cleared on disable"
        );
        // content_hint and content_purpose values are preserved (they're just
        // not marked for re-send). This matches the spec: "void" means the
        // compositor should not act on them, not that they must be zeroed.
    }

