// NOTE: This handler is only active when `emulate_compat_shims` is enabled.
// It emulates a guest zwp_text_input_manager_v3 object by instantiating host
// zwp_text_input_v1 under the hood. It can be removed once all target host
// compositors natively support zwp_text_input_v3.
pub struct TextInputManagerV3Handler;
impl zwp_text_input_manager_v3::ZwpTextInputManagerV3Handler for TextInputManagerV3Handler {
    fn on_get_text_input(&mut self, ctx: &mut Context, id: u32, seat: u32) -> Action {
        let host_v1_id = ctx.shadow_table.allocate_host_id();
        let host_ext_id = ctx.shadow_table.allocate_host_id();

        if let Some(host_manager_id) = ctx.host_text_input_manager_v1_id {
            let mut builder = MessageBuilder::new();
            builder.write_u32(host_v1_id);
            let full_msg = builder.build_message(host_manager_id, ZWP_TEXT_INPUT_MANAGER_V1_REQ_CREATE_TEXT_INPUT);
            ctx.client_to_host_queue.push((full_msg, Vec::new()));
        }

        if let Some(host_ext_manager_id) = ctx.host_text_input_extension_v1_id {
            let mut builder = MessageBuilder::new();
            builder.write_u32(host_ext_id);
            builder.write_u32(host_v1_id);
            let full_msg = builder.build_message(host_ext_manager_id, ZCR_TEXT_INPUT_EXTENSION_V1_REQ_GET_EXTENDED_TEXT_INPUT);
            ctx.client_to_host_queue.push((full_msg, Vec::new()));
        }

        ctx.shadow_table.map_id(id, host_v1_id);
        ctx.shadow_table
            .track_interface(id, "zwp_text_input_v3".to_string());
        ctx.shadow_table
            .track_host_interface(host_v1_id, "zwp_text_input_v1".to_string());
        ctx.shadow_table
            .track_host_interface(host_ext_id, "zcr_extended_text_input_v1".to_string());

        let active_surface = ctx.active_surface_for_seat.get(&seat).copied();

        ctx.text_inputs.insert(
            id,
            crate::state::TextInputState {
                host_v1_id,
                host_ext_id,
                guest_seat: seat,
                active_surface,
                ..Default::default()
            },
        );

        Action::Drop
    }
}

// NOTE: This handler is only active when `emulate_compat_shims` is enabled.
// It translates guest zwp_text_input_v3 requests to host zwp_text_input_v1 requests.
// It can be removed once all target host compositors natively support
// zwp_text_input_v3.
pub struct TextInputV3Handler;
impl zwp_text_input_v3::ZwpTextInputV3Handler for TextInputV3Handler {
    fn on_enable(&mut self, ctx: &mut Context) -> Action {
        let guest_id = ctx.last_sender_id;
        if let Some(state) = ctx.text_inputs.get_mut(&guest_id) {
            state.enabled = true;
            state.enabled_changed = true;
        }
        Action::Drop
    }

    fn on_disable(&mut self, ctx: &mut Context) -> Action {
        let guest_id = ctx.last_sender_id;
        if let Some(state) = ctx.text_inputs.get_mut(&guest_id) {
            state.enabled = false;
            state.enabled_changed = true;
            // Per the zwp_text_input_v3 spec: "after the text input was disabled
            // [...] the state of the text input is considered void." Clear any
            // pending state so that a subsequent enable+commit cycle doesn't
            // re-send stale content types, surrounding text, or cursor rects.
            state.surrounding_text = None;
            state.content_type_changed = false;
            state.cursor_rect = None;
        }
        Action::Drop
    }

    fn on_set_surrounding_text(
        &mut self,
        ctx: &mut Context,
        text: &String,
        cursor: i32,
        anchor: i32,
    ) -> Action {
        let guest_id = ctx.last_sender_id;
        if let Some(state) = ctx.text_inputs.get_mut(&guest_id) {
            state.surrounding_text = Some((text.clone(), cursor, anchor));
        }
        Action::Drop
    }

    fn on_set_text_change_cause(&mut self, ctx: &mut Context, cause: u32) -> Action {
        let guest_id = ctx.last_sender_id;
        if let Some(state) = ctx.text_inputs.get_mut(&guest_id) {
            state.text_change_cause = cause;
        }
        Action::Drop
    }

    fn on_set_content_type(&mut self, ctx: &mut Context, hint: u32, purpose: u32) -> Action {
        let guest_id = ctx.last_sender_id;
        if let Some(state) = ctx.text_inputs.get_mut(&guest_id) {
            state.content_hint = hint;
            state.content_purpose = purpose;
            state.content_type_changed = true;
        }
        Action::Drop
    }

    fn on_set_cursor_rectangle(
        &mut self,
        ctx: &mut Context,
        x: i32,
        y: i32,
        width: i32,
        height: i32,
    ) -> Action {
        let guest_id = ctx.last_sender_id;
        if let Some(state) = ctx.text_inputs.get_mut(&guest_id) {
            state.cursor_rect = Some((x, y, width, height));
        }
        Action::Drop
    }

    fn on_commit(&mut self, ctx: &mut Context) -> Action {
        // This handler is only reachable when emulate_compat_shims is enabled (the v3
        // manager global is only advertised in that mode). Guard at runtime so that a
        // future code change exposing v3 without shims doesn't silently send v1
        // messages to a host that has no v1 text input bound.
        if !ctx.emulate_compat_shims {
            log::error!(
                "TextInputV3Handler::on_commit called but emulate_compat_shims is disabled; \
                 this is a bug — the v3 manager should not have been advertised"
            );
            return Action::Drop;
        }
        let guest_id = ctx.last_sender_id;

        // BORROW-SPLIT INVARIANT: This block borrows `ctx.text_inputs` mutably
        // while pushing to `ctx.client_to_host_queue` and reading from
        // `ctx.shadow_table`. This is safe because Rust's borrow checker treats
        // struct fields independently — the queues and shadow table are disjoint
        // from `text_inputs`. If these are ever refactored into the same
        // container, this code must be restructured.
        if let Some(state) = ctx.text_inputs.get_mut(&guest_id) {
            let host_v1_id = state.host_v1_id;
            let host_seat = ctx.shadow_table.get_host_id(state.guest_seat).unwrap_or(0);
            let host_surface = state
                .active_surface
                .and_then(|s| ctx.shadow_table.get_host_id(s))
                .unwrap_or(0);

            // Handle activation/deactivation transitions.
            // Under zwp_text_input_v1, IME activation requires both a valid seat and a valid surface
            // focused object. If those mappings are not yet resolved on the host side, we must defer
            // sending the activate request to the host.
            // Once the mappings are successfully resolved and the message is successfully queued,
            // we clear the `enabled_changed` flag to prevent duplicate state synchronization.
            //
            // Note: if the mappings are not yet resolved, `enabled_changed` remains true. The
            // activation will be retried on the next keyboard enter event (see keyboard.rs
            // on_enter), which re-triggers pending text input commits when surface focus is
            // established.
            if state.enabled_changed {
                if state.enabled {
                    if host_seat != 0 && host_surface != 0 {
                        let mut builder = MessageBuilder::new();
                        builder.write_u32(host_seat);
                        builder.write_u32(host_surface);
                        let full_msg = builder.build_message(host_v1_id, ZWP_TEXT_INPUT_V1_REQ_ACTIVATE);
                        ctx.client_to_host_queue.push((full_msg, Vec::new()));
                        state.enabled_changed = false;
                    } else {
                        log::debug!(
                            "on_commit: deferring activation for text_input guest_id={}; \
                             host_seat={}, host_surface={} (not yet resolved)",
                            guest_id, host_seat, host_surface
                        );
                    }
                } else {
                    // Deactivation: requires a valid seat to address the message.
                    // If host_seat is not yet resolved, defer — like activation, this
                    // is an unusual race (deactivate before seat mapping is established).
                    // enabled_changed remains true; a subsequent commit once the seat is
                    // known will send the deactivate. If the seat is destroyed before
                    // that happens, the IME on the host side will be cleaned up anyway
                    // by the compositor when the seat disappears.
                    if host_seat != 0 {
                        let mut builder = MessageBuilder::new();
                        builder.write_u32(host_seat);
                        let full_msg = builder.build_message(host_v1_id, ZWP_TEXT_INPUT_V1_REQ_DEACTIVATE);
                        ctx.client_to_host_queue.push((full_msg, Vec::new()));
                        state.enabled_changed = false;
                    } else {
                        log::debug!(
                            "on_commit: deferring deactivation for text_input guest_id={}; \
                             host_seat not yet resolved",
                            guest_id
                        );
                    }
                }
            }

            if let Some((text, cursor, anchor)) = state.surrounding_text.take() {
                let mut builder = MessageBuilder::new();
                builder.write_string(&text);
                // v3 uses i32 for cursor/anchor; v1 uses u32. Negative values
                // (e.g. "not set" sentinel) wrap to large positive u32 values.
                // This matches the C sommelier reference behavior.
                builder.write_u32(cursor as u32);
                builder.write_u32(anchor as u32);
                let full_msg = builder.build_message(host_v1_id, ZWP_TEXT_INPUT_V1_REQ_SET_SURROUNDING_TEXT);
                ctx.client_to_host_queue.push((full_msg, Vec::new()));
            }

            if state.content_type_changed {
                let mut builder = MessageBuilder::new();
                builder.write_u32(state.content_hint);
                builder.write_u32(state.content_purpose);
                let full_msg = builder.build_message(host_v1_id, ZWP_TEXT_INPUT_V1_REQ_SET_CONTENT_TYPE);
                ctx.client_to_host_queue.push((full_msg, Vec::new()));

                // Map v3 content_purpose to zcr_extended_text_input_v1::set_input_type.
                // v3 purposes (per spec): normal(0), alpha(1), digits(2), number(3),
                // phone(4), url(5), email(6), name(7), password(8), pin(9),
                // date(10), time(11), datetime(12), terminal(13).
                let input_type = match state.content_purpose {
                    0 | 1 | 7 => 1, // TEXT (normal, alpha, name)
                    2 | 3 => 2,     // NUMBER (digits, number)
                    4 => 3,         // TELEPHONE (phone)
                    5 => 4,         // URL
                    6 => 5,         // EMAIL
                    8 => 6,         // PASSWORD
                    9 => 2,         // NUMBER (pin — numeric password)
                    // date(10), time(11), datetime(12), terminal(13) → TEXT
                    _ => 1,
                };

                let input_mode = 0; // default
                let input_flags = 0;
                let learning_mode = 0;
                let inline_composition_support = 0;

                let mut ext_builder = MessageBuilder::new();
                ext_builder.write_u32(input_type);
                ext_builder.write_u32(input_mode);
                ext_builder.write_u32(input_flags);
                ext_builder.write_u32(learning_mode);
                ext_builder.write_u32(inline_composition_support);
                let ext_msg = ext_builder.build_message(state.host_ext_id, ZCR_EXTENDED_TEXT_INPUT_V1_REQ_SET_INPUT_TYPE);
                ctx.client_to_host_queue.push((ext_msg, Vec::new()));

                state.content_type_changed = false;
            }

            if let Some((x, y, w, h)) = state.cursor_rect.take() {
                let mut builder = MessageBuilder::new();
                builder.write_i32(x);
                builder.write_i32(y);
                builder.write_i32(w);
                builder.write_i32(h);
                let full_msg = builder.build_message(host_v1_id, ZWP_TEXT_INPUT_V1_REQ_SET_CURSOR_RECTANGLE);
                ctx.client_to_host_queue.push((full_msg, Vec::new()));
            }

            // Only send commit_state when activation was not deferred. If
            // enabled_changed is still true, the activation wasn't sent yet
            // and commit_state would target an inactive text input object on
            // the host, which is at best a no-op and at worst a protocol error.
            if !state.enabled_changed {
                let mut builder = MessageBuilder::new();
                builder.write_u32(0); // serial
                let full_msg = builder.build_message(host_v1_id, ZWP_TEXT_INPUT_V1_REQ_COMMIT_STATE);
                ctx.client_to_host_queue.push((full_msg, Vec::new()));
            }
        }

        Action::Drop
    }

    fn on_destroy(&mut self, ctx: &mut Context) -> Action {
        let guest_id = ctx.last_sender_id;
        if let Some(state) = ctx.text_inputs.remove(&guest_id) {
            // If the text input was enabled, send deactivate to the host so the
            // compositor releases IME resources.
            if state.enabled {
                if let Some(host_seat) = ctx.shadow_table.get_host_id(state.guest_seat) {
                    let mut builder = MessageBuilder::new();
                    builder.write_u32(host_seat);
                    let msg = builder.build_message(state.host_v1_id, ZWP_TEXT_INPUT_V1_REQ_DEACTIVATE);
                    ctx.client_to_host_queue.push((msg, Vec::new()));

                    // Follow up with commit_state per the v1 protocol pattern.
                    let mut builder = MessageBuilder::new();
                    builder.write_u32(0); // serial
                    let msg = builder.build_message(state.host_v1_id, ZWP_TEXT_INPUT_V1_REQ_COMMIT_STATE);
                    ctx.client_to_host_queue.push((msg, Vec::new()));
                }
            }

            // Clean up active_surface_for_seat: if this was the only text input
            // tracking this seat, remove the stale surface entry. Without this,
            // a new text input created for the same seat could inherit a surface
            // that no longer exists.
            //
            // Only remove if no other text input is tracking the same seat.
            let seat_still_tracked = ctx.text_inputs.values().any(|ti| ti.guest_seat == state.guest_seat);
            if !seat_still_tracked {
                ctx.active_surface_for_seat.remove(&state.guest_seat);
            }

            // Clean up the shadow table entries for both host objects.
            // v1 has no destroy request, so we just forget the mappings.
            // The host compositor will clean up the v1 objects when the
            // connection closes.
            ctx.shadow_table.remove_id(guest_id);
            ctx.shadow_table.remove_host_interface(state.host_ext_id);

            log::debug!("TextInputV3 destroyed: guest_id={}, host_v1_id={}, host_ext_id={}", guest_id, state.host_v1_id, state.host_ext_id);
        }
        // Drop — the guest's v3 destroy is consumed by the shim; there's no
        // corresponding v1 destroy request to forward.
        Action::Drop
    }
}

